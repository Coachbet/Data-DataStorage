"""Report: the written report, as a PDF when the team adds one, else the Markdown draft."""

import re

import streamlit as st

import data
import ui

PDF = data.PROJECT / "report" / "report.pdf"
DECISIONS = data.PROJECT / "report" / "decision_record.pdf"
DRAFT = data.DOCS / "report" / "report.md"
IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)]+)\)")


def render() -> None:
    ui.header(
        "Section 8 · Report",
        "The full report",
        "The written report that goes with this site: question, data, method, results, limits.",
    )
    ui.section("report", "s8-1")
    if PDF.exists():
        left, right = st.columns(2)
        left.download_button(
            "Download the report (PDF)", PDF.read_bytes(), "report.pdf", "application/pdf"
        )
        if DECISIONS.exists():
            right.download_button(
                "Download the decision record (PDF)",
                DECISIONS.read_bytes(),
                "decision_record.pdf",
                "application/pdf",
            )
        st.iframe(PDF, height=1000)
        return

    if not DRAFT.is_file():
        ui.callout(
            "The report is not here yet. Put the compiled LaTeX report at "
            "<code>report/report.pdf</code>, or run <code>make analysis</code> to generate the "
            "draft in <code>docs/report/report.md</code>.",
            warn=True,
        )
        return
    ui.callout(
        "This is the current draft generated by the pipeline (<code>docs/report/report.md</code>). "
        "To show the final LaTeX report instead, put the compiled file at "
        "<code>report/report.pdf</code>: this page will display it and offer a download.",
        warn=True,
    )
    text = DRAFT.read_text(encoding="utf-8")
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    # Render Markdown in chunks so figures can be shown with st.image.
    pos = 0
    for match in IMAGE.finditer(text):
        st.markdown(_tidy(text[pos : match.start()]), unsafe_allow_html=True)
        path = (DRAFT.parent / match.group(2)).resolve()
        if path.exists():
            st.image(str(path), width="stretch")
        pos = match.end()
    st.markdown(_tidy(text[pos:]), unsafe_allow_html=True)


def _tidy(chunk: str) -> str:
    return chunk
