"""Review kit for the candidate table. Every coder sheet here is synthetic.

No sheet filled by a team member exists in this repository. The sheets below are
generated by mechanical rules inside temporary folders, only to exercise the code.
"""

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd
import pytest
from vote_transfer.application.positions import load_candidate_positions
from vote_transfer.application.review import (
    BLIND_COLUMNS,
    coding_agreement,
    coding_sheet,
    load_coding_sheet,
    reference_quality,
    weighted_kappa,
)

REVIEW_DIR = Path(__file__).resolve().parents[1] / "data" / "reference" / "review"
FAMILIES = ["Far left", "Left", "Centre-left", "Centre", "Centre-right", "Right", "Far right"]


def synthetic_sheet(path, rule):
    """Fill the blind template with a mechanical rule; not a human judgement."""
    sheet = pd.read_csv(REVIEW_DIR / "coding_sheet_template.csv", keep_default_na=False)
    sheet["political_family"] = [rule(i) for i in range(len(sheet))]
    sheet.to_csv(path, index=False)
    return path


def test_template_is_blind_and_matches_the_reference_rows():
    template = pd.read_csv(REVIEW_DIR / "coding_sheet_template.csv", keep_default_na=False)
    positions = load_candidate_positions()
    assert len(template) == 61
    assert template[["year", "candidate_id"]].equals(positions[["year", "candidate_id"]])
    assert not set(BLIND_COLUMNS) & set(template.columns) - {"political_family"}
    assert template.political_family.eq("").all()  # empty: to be filled by the coder
    for hidden in ("ideology_score", "alternative_family", "classification_note", "review_status"):
        assert hidden not in template
    # The committed template is exactly what the code generates.
    pd.testing.assert_frame_equal(template, coding_sheet(positions))
    # No leak through free text: no family name appears anywhere in the sheet.
    text = (REVIEW_DIR / "coding_sheet_template.csv").read_text(encoding="utf-8")
    assert not any(f",{family}," in text for family in FAMILIES)


def test_quadratic_weighted_kappa_matches_hand_calculations():
    # Two categories: weighted kappa equals Cohen's kappa. po = 0.7, pe = 0.5.
    a = [1] * 25 + [2] * 25
    b = [1] * 20 + [2] * 5 + [1] * 10 + [2] * 15
    assert weighted_kappa(a, b, categories=2) == pytest.approx(0.4)
    # Three categories, worked by hand in the docstring of weighted_kappa: 2/7.
    assert weighted_kappa([1, 1, 2, 2, 3, 3], [1, 2, 2, 2, 3, 1], categories=3) == pytest.approx(
        2 / 7
    )
    assert weighted_kappa([1, 2, 3], [1, 2, 3], categories=3) == pytest.approx(1)
    assert weighted_kappa([1, 2, 3], [3, 2, 1], categories=3) == pytest.approx(-1)
    # Both coders constant: chance agreement is total, kappa is undefined.
    assert weighted_kappa([4, 4], [4, 4], categories=7) is None
    with pytest.raises(ValueError):
        weighted_kappa([1, 2], [1], categories=7)
    with pytest.raises(ValueError):
        weighted_kappa([0, 8], [1, 2], categories=7)


def test_far_disagreements_cost_more_than_adjacent_ones():
    base = [1, 2, 3, 4, 5, 6, 7]
    adjacent = weighted_kappa(base, [2, 2, 3, 4, 5, 6, 7], categories=7)
    distant = weighted_kappa(base, [7, 2, 3, 4, 5, 6, 7], categories=7)
    assert distant < adjacent < 1


def test_agreement_report_on_synthetic_sheets(tmp_path):
    positions = load_candidate_positions()
    a = load_coding_sheet(synthetic_sheet(tmp_path / "a.csv", lambda i: FAMILIES[i % 7]), positions)
    b = load_coding_sheet(
        synthetic_sheet(
            tmp_path / "b.csv",
            lambda i: "Unclassified" if i == 0 else FAMILIES[(i + (i % 5 == 0)) % 7],
        ),
        positions,
    )
    report = coding_agreement(a, b)
    assert report["rows"] == 61
    disagreements = report["disagreements"]
    assert len(disagreements) == 13  # every fifth row, 0 to 60
    assert report["agreement_pct"] == pytest.approx(100 * 48 / 61)
    assert report["rows_scored_by_both"] == 60  # row 0 is Unclassified for coder b
    assert -1 <= report["quadratic_weighted_kappa"] < 1
    matrix = pd.DataFrame(
        report["confusion_matrix"]["counts"],
        index=report["confusion_matrix"]["labels"],
        columns=report["confusion_matrix"]["labels"],
    )
    assert matrix.to_numpy().sum() == 61
    assert matrix.loc["Far left", "Unclassified"] == 1
    assert {"year", "candidate_id", "coder_a", "coder_b", "steps_apart"} <= set(disagreements[0])
    assert disagreements[0]["steps_apart"] is None  # one side has no score
    same = coding_agreement(a, a)
    assert same["agreement_pct"] == 100 and same["disagreements"] == []
    assert same["quadratic_weighted_kappa"] == pytest.approx(1)


@pytest.mark.parametrize("fault", ["blank", "unknown", "missing_row", "extra_row", "reordered_id"])
def test_incomplete_or_invalid_sheets_are_rejected(tmp_path, fault):
    positions = load_candidate_positions()
    sheet = pd.read_csv(
        synthetic_sheet(tmp_path / "a.csv", lambda i: "Centre"), keep_default_na=False
    )
    if fault == "blank":
        sheet.loc[3, "political_family"] = ""
    elif fault == "unknown":
        sheet.loc[3, "political_family"] = "Ecologist"
    elif fault == "missing_row":
        sheet = sheet.iloc[1:]
    elif fault == "extra_row":
        sheet = pd.concat([sheet, sheet.iloc[[0]]])
    else:
        sheet.loc[3, "candidate_id"] = "someone-else"
    sheet.to_csv(tmp_path / "bad.csv", index=False)
    with pytest.raises(ValueError):
        load_coding_sheet(tmp_path / "bad.csv", positions)


def test_cli_writes_the_agreement_report_end_to_end(tmp_path):
    a = synthetic_sheet(tmp_path / "a.csv", lambda i: FAMILIES[i % 7])
    b = synthetic_sheet(tmp_path / "b.csv", lambda i: FAMILIES[(i + (i % 4 == 0)) % 7])
    output = tmp_path / "coding_agreement.json"
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "vote_transfer.cli",
            "review-agreement",
            "--coder-a",
            str(a),
            "--coder-b",
            str(b),
            "--output",
            str(output),
        ],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    report = json.loads(output.read_text())
    assert report["rows"] == 61
    assert report["coder_a_file"] == "a.csv" and report["coder_b_file"] == "b.csv"
    assert len(report["disagreements"]) == 16
    # The default output location must never be touched by a test.
    assert "reports/results" not in str(output)


def test_real_agreement_report_is_absent_until_humans_code():
    """Guard against invented coder data: no agreement file ships before the review."""
    results = Path(__file__).resolve().parents[1] / "reports" / "results"
    positions = load_candidate_positions()
    if not positions.review_status.eq("reviewed").any():
        assert not (results / "coding_agreement.json").exists()


def test_reference_quality_reports_consistency_and_completeness():
    quality = reference_quality(load_candidate_positions())
    assert quality["rows"] == 61
    assert sorted(
        item["party"] for item in quality["consistency"]["parties_coded_differently"]
    ) == [
        "PS",
        "UDF",
    ]
    ps = next(i for i in quality["consistency"]["parties_coded_differently"] if i["party"] == "PS")
    assert {row["family"] for row in ps["rows"]} == {"Centre-left", "Left"}
    assert quality["completeness"]["rows_without_score"] == 2
    assert {(r["year"], r["candidate_id"]) for r in quality["completeness"]["missing"]} == {
        (2012, "jacques-cheminade"),
        (2017, "jacques-cheminade"),
    }
    assert quality["review_status"] == {"draft": 59, "unresolved": 2}
    assert quality["rows_with_alternative"] == 41
    assert quality["accuracy"]["status"] == "pending: two-coder review not done"
